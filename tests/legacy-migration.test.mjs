import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
import { hashPassword as betterAuthHashPassword, verifyPassword as betterAuthVerifyPassword } from "@better-auth/utils/password";
import { verifyBetterAuthPassword } from "../backend/legacy-password.ts";
import { runLegacyMigration } from "../backend/legacy-migration-core.ts";

const markerKey = "liveloot_legacy_migration";
const password = "Compatibility-Test-Password-2026!";
const email = `migration-${randomUUID()}@example.test`;

function makeDependencies(overrides = {}) {
  const legacy = {
    id: `legacy-${randomUUID()}`,
    name: "Migration Test",
    emailVerified: true,
    banned: false,
    banExpires: null,
    passwordHash: "",
  };
  const users = new Map();
  const profiles = new Map();
  const state = { created: 0, resent: 0, failSyncCount: 0 };

  const dependencies = {
    async findLegacyAccount() {
      return legacy;
    },
    verifyPassword: verifyBetterAuthPassword,
    async findSupabaseUser(normalizedEmail) {
      return users.get(normalizedEmail) ?? null;
    },
    async createSupabaseUser(input) {
      state.created += 1;
      const user = {
        id: `supabase-${randomUUID()}`,
        email_confirmed_at: input.emailConfirmed ? new Date().toISOString() : null,
        app_metadata: { [markerKey]: { status: "pending", legacyUserId: input.legacyUserId } },
      };
      users.set(input.email, user);
      return user;
    },
    async syncLegacyProfile(userId, legacyUserId) {
      if (state.failSyncCount > 0) {
        state.failSyncCount -= 1;
        return false;
      }
      profiles.set(userId, { id: userId, legacy_user_id: legacyUserId });
      return true;
    },
    async markMigrationComplete(userId, legacyUserId) {
      const user = [...users.values()].find((entry) => entry.id === userId);
      if (!user || user.app_metadata?.[markerKey]?.legacyUserId !== legacyUserId) return false;
      user.app_metadata[markerKey].status = "complete";
      return true;
    },
    async resendConfirmation() {
      state.resent += 1;
    },
    users,
    profiles,
    state,
    legacy,
    ...overrides,
  };
  return dependencies;
}

test("scrypt hashes generated by Better Auth verify without exposing the hash", async () => {
  const hash = await betterAuthHashPassword(password);
  assert.equal(await betterAuthVerifyPassword(hash, password), true);
  assert.equal(await verifyBetterAuthPassword(password, hash), true);
  assert.equal(await verifyBetterAuthPassword(`${password}wrong`, hash), false);
  assert.equal(await verifyBetterAuthPassword(password, "not-a-better-auth-hash"), false);
});

test("creates a Supabase identity and associates the legacy profile id", async () => {
  const dependencies = makeDependencies();
  dependencies.legacy.passwordHash = await betterAuthHashPassword(password);

  const result = await runLegacyMigration(email, password, `create:${randomUUID()}`, "https://app.example.test", dependencies);

  assert.equal(result, "migrated");
  assert.equal(dependencies.state.created, 1);
  const [profile] = dependencies.profiles.values();
  assert.equal(profile.legacy_user_id, dependencies.legacy.id);
});

test("does not overwrite a Supabase account that already uses the email", async () => {
  const existing = { id: `existing-${randomUUID()}`, email_confirmed_at: new Date().toISOString(), app_metadata: {} };
  const dependencies = makeDependencies({
    async findSupabaseUser() {
      return existing;
    },
  });
  dependencies.legacy.passwordHash = await betterAuthHashPassword(password);

  const result = await runLegacyMigration(email, password, `conflict:${randomUUID()}`, "https://app.example.test", dependencies);

  assert.equal(result, "conflict");
  assert.equal(dependencies.state.created, 0);
  assert.equal(dependencies.profiles.size, 0);
  assert.deepEqual(existing.app_metadata, {});
});

test("resumes safely after a partial profile-sync failure", async () => {
  const dependencies = makeDependencies();
  dependencies.legacy.passwordHash = await betterAuthHashPassword(password);
  dependencies.state.failSyncCount = 1;
  const requestKey = `retry:${randomUUID()}`;

  const firstResult = await runLegacyMigration(email, password, requestKey, "https://app.example.test", dependencies);
  const retryResult = await runLegacyMigration(email, password, requestKey, "https://app.example.test", dependencies);

  assert.equal(firstResult, "unavailable");
  assert.equal(retryResult, "migrated");
  assert.equal(dependencies.state.created, 1);
  const [profile] = dependencies.profiles.values();
  assert.equal(profile.legacy_user_id, dependencies.legacy.id);
});

test("requires email confirmation and requests a confirmation message", async () => {
  const dependencies = makeDependencies();
  dependencies.legacy.emailVerified = false;
  dependencies.legacy.passwordHash = await betterAuthHashPassword(password);

  const result = await runLegacyMigration(email, password, `confirm:${randomUUID()}`, "https://app.example.test", dependencies);

  assert.equal(result, "confirmation_required");
  assert.equal(dependencies.state.resent, 1);
});
